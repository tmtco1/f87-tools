#!/usr/bin/env python3
"""Generate web/js/fw-data.js for the web firmware patcher from the built patch blobs.

Contains no AULA code: only the SHA-256 of the base firmware's code areas (to recognise it) and our
own patch blobs (boot animations, Game of Life; Bad Apple only with --badapple, since that blob is an
encoding of someone else's video).

usage: build_web_data.py [--base base_f87_decrypted.bin] [--badapple]
Build the blobs first: effects/anim/build.sh <name>, effects/life/build.py (and effects/badapple/build.py VIDEO).
"""
import argparse
import hashlib
import json
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
HERE = os.path.dirname(TOOLS)          # repo root
sys.path.insert(0, TOOLS)
import patch_firmware as pf  # noqa: E402

# Byte ranges hashed to recognise the base firmware (after undoing our patches): the code, and the free
# areas our patches use. The settings sectors 0xB400-0xDBFF differ per keyboard and are left out.
CODE_RANGES = [(0x0000, 0xB400), (0xDC00, 0xEFFB)]


def blob(path):
    code = pf.load_ihx(path)
    lo, hi = min(code), max(code)
    data = bytes(code.get(a, 0) for a in range(lo, hi + 1))
    return {"addr": lo, "hex": data.hex()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default=os.path.join(HERE, "base_f87_decrypted.bin"))
    ap.add_argument("--badapple", action="store_true", help="also bundle effects/badapple/build/badapple.ihx")
    a = ap.parse_args()
    base = open(a.base, "rb").read()
    if hashlib.md5(base).hexdigest() != pf.KNOWN_MD5:
        sys.exit(f"{a.base} is not the known base image")
    h = hashlib.sha256(b"".join(base[s:e] for s, e in CODE_RANGES)).hexdigest()

    anims = {}
    for key, p in pf.BOOT_ANIMS.items():
        path = os.path.join(HERE, p["ihx"])
        if not os.path.exists(path):
            sys.exit(f"{p['ihx']} missing: run effects/anim/build.sh first")
        anims[key] = {"about": p["about"], "step": p["step"], "fade": p["fade"], **blob(path)}
    effects = {}
    for key in ("life", "badapple") if a.badapple else ("life",):
        path = os.path.join(HERE, pf.EFFECT_PRESETS[key])
        if not os.path.exists(path):
            sys.exit(f"{pf.EFFECT_PRESETS[key]} missing: build it first")
        effects[key] = blob(path)

    out = os.path.join(HERE, "web", "js", "fw-data.js")
    with open(out, "w") as f:
        f.write("// Generated by build_web_data.py. Do not edit.\n")
        f.write(f"export const BASE_CODE_SHA256 = {json.dumps(h)};\n")
        f.write(f"export const CODE_RANGES = {json.dumps(CODE_RANGES)};\n")
        f.write(f"export const BOOT_ANIMS = {json.dumps(anims, indent=1)};\n")
        f.write(f"export const EFFECT_BLOBS = {json.dumps(effects)};\n")
    print(f"wrote {os.path.relpath(out)}: {len(anims)} boot animations, effects {sorted(effects)}")


if __name__ == "__main__":
    main()
